def _pcdb_verdict(terminology_text, ctx):
    """Resolve a distributor's terminology text against the PCdb mirror, then apply the rules."""
    hit = ctx["pcdb_by_name"].get(pt.normalize_terminology_name(terminology_text))
    if not hit:
        return None
    terminology_id, category_id = hit
    return pt.classify_pcdb_terminology(
        part_terminology_id=terminology_id, category_id=category_id
    )


def _premier(row, ctx):
    """
    Premier ships both a PCdb terminology name and a PCdb category name. Terminology is tried
    first because it is the only one of the two that can split "Tire and Wheel" into an actual
    wheel, an actual tire, and the lug nuts and caps filed beside them.
    """
    verdict = _pcdb_verdict(row["part_terminology"], ctx)
    if verdict is not None:
        return verdict
    return pt.classify_premier_category(row["part_category"])


def _meyer(row, ctx):
    """
    Meyer's ``sub_category`` is the PCdb terminology vocabulary uppercased, and can pack several
    terminologies into one semicolon-joined value ("WHEEL LUG NUT LOCK;WHEEL LOCK"). Every token
    is resolved; a value only produces a verdict when all of the tokens that resolve agree, so a
    row that is half wheel and half something else is left alone rather than taking the first.
    """
    verdicts = [_pcdb_verdict(token, ctx) for token in pt.split_multi_value(row["sub_category"])]
    resolved = {verdict.product_type for verdict in verdicts if verdict is not None}
    if len(resolved) == 1:
        product_type = resolved.pop()
        source = next(v.source for v in verdicts if v is not None and v.product_type == product_type)
        return pt.Verdict(product_type, source)
    if resolved:
        return None  # tokens disagree -- say nothing
    return pt.classify_meyer_category(row["category"])


