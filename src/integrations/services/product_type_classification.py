SOURCES_BY_NAME = {source.name: source for source in SOURCES}


def _load_pcdb_lookup() -> typing.Dict[str, typing.Tuple[int, typing.Optional[int]]]:
    """
    ``normalized terminology name -> (part_terminology_id, category_id)`` for the whole PCdb
    mirror (40,646 rows, small enough to hold). Aliases are included so a distributor using an
    accepted synonym still resolves; a name that is both a term and someone else's alias keeps
    the real term.
    """
    lookup: typing.Dict[str, typing.Tuple[int, typing.Optional[int]]] = {}
    rows = src_models.PcdbTerminologyFlat.objects.values(
        "part_terminology_id", "name", "category_id", "aliases"
    )
    for row in rows:
        for alias in row.get("aliases") or []:
            key = pt.normalize_terminology_name(alias)
            if key:
                lookup.setdefault(key, (row["part_terminology_id"], row["category_id"]))
    for row in rows:
        key = pt.normalize_terminology_name(row["name"])
        if key:
            lookup[key] = (row["part_terminology_id"], row["category_id"])
    return lookup


def _ensure_staging_table() -> None:
    with connection.cursor() as cursor:
        cursor.execute(
            "CREATE UNLOGGED TABLE IF NOT EXISTS {} ("
            "  master_part_id bigint NOT NULL,"
            "  provider_id integer NOT NULL,"
            "  source_name text NOT NULL,"
            "  product_type varchar(16) NOT NULL,"
            "  product_type_source varchar(64) NOT NULL,"
            "  tier smallint NOT NULL"
            ")".format(STAGING_TABLE)
        )
        cursor.execute(
            "CREATE INDEX IF NOT EXISTS {t}_master_part_idx ON {t} (master_part_id)".format(
                t=STAGING_TABLE
            )
        )


def _clear_staging(source_names: typing.Sequence[str]) -> None:
    with connection.cursor() as cursor:
        cursor.execute(
            "DELETE FROM {} WHERE source_name = ANY(%s)".format(STAGING_TABLE), [list(source_names)]
        )


def collect_source(
    source: _Source,
    ctx: typing.Dict,
    limit: typing.Optional[int] = None,
) -> typing.Dict[str, int]:
    """
    Page one distributor's provider_parts, classify each, and stage the verdicts.

    Returns counts for the run report. ``scanned`` includes rows whose raw row did not join and
    rows the rules declined -- both are gaps worth seeing, and they are counted separately.
    """
    provider = src_models.Providers.objects.filter(kind=source.provider_kind).first()
    if not provider:
        logger.info("%s %s: no provider row, skipped.", _LOG_PREFIX, source.name)
        return {"scanned": 0, "unjoined": 0, "undecided": 0, "staged": 0}

    sql = source.batch_sql()
    stats = {"scanned": 0, "unjoined": 0, "undecided": 0, "staged": 0}
    last_id = 0
    while True:
        batch_limit = BATCH_SIZE
        if limit is not None:
            remaining = limit - stats["scanned"]
            if remaining <= 0:
                break
            batch_limit = min(BATCH_SIZE, remaining)

        with connection.cursor() as cursor:
            cursor.execute(
                sql,
                {"provider_id": provider.id, "last_id": last_id, "limit": batch_limit},
            )
            column_names = [column[0] for column in cursor.description]
            rows = cursor.fetchall()
        if not rows:
            break

        staged_rows = []
        for raw_row in rows:
            row = dict(zip(column_names, raw_row))
            last_id = max(last_id, row["id"])
            stats["scanned"] += 1
            if not row["joined"]:
                stats["unjoined"] += 1
                continue
            verdict = source.classify(row, ctx)
            if verdict is None:
                stats["undecided"] += 1
                continue
            staged_rows.append(
                (
                    row["master_part_id"],
                    provider.id,
                    source.name,
                    verdict.product_type,
                    verdict.source,
                    pt.tier_for_source(verdict.source),
                )
            )

        if staged_rows:
            # execute_values, not executemany: psycopg2's executemany issues one round trip per
            # row, and this stages ~2.7M of them.
            with connection.cursor() as cursor:
                psycopg2_extras.execute_values(
                    cursor,
                    "INSERT INTO {} (master_part_id, provider_id, source_name, product_type,"
                    " product_type_source, tier) VALUES %s".format(STAGING_TABLE),
                    staged_rows,
                    page_size=1000,
                )
            stats["staged"] += len(staged_rows)

        logger.info(
            "%s %s: scanned=%s staged=%s unjoined=%s undecided=%s (last_id=%s)",
            _LOG_PREFIX, source.name, stats["scanned"], stats["staged"],
            stats["unjoined"], stats["undecided"], last_id,
        )
        if len(rows) < batch_limit:
            break
    return stats


# Best tier wins; that tier must be unanimous. ``COUNT(DISTINCT product_type) = 1`` is the whole
# safety property -- a master part whose best-tier distributors disagree gets no value at all.
# Inner CTEs are named best_tier/resolved so that callers wrapping this as `WITH agreed AS (...)`
# do not shadow a name it uses itself. When distinct_types = 1 every row shares one product_type,
# so MIN(product_type_source) is just a deterministic pick among sources that already agree.
_RESOLVE_SELECT = """
WITH best_tier AS (
    SELECT master_part_id, MIN(tier) AS tier
    FROM {t}
    GROUP BY master_part_id
),
resolved AS (
    SELECT
        c.master_part_id,
        MIN(c.product_type) AS product_type,
        MIN(c.product_type_source) AS product_type_source,
        COUNT(DISTINCT c.product_type) AS distinct_types
    FROM {t} c
    JOIN best_tier b ON b.master_part_id = c.master_part_id AND b.tier = c.tier
    GROUP BY c.master_part_id
)
SELECT * FROM resolved
""".format(t=STAGING_TABLE)


def resolution_report() -> typing.Dict[str, typing.Any]:
    """Counts of what a resolve would write, without writing anything."""
    with connection.cursor() as cursor:
        cursor.execute(
            "WITH agreed AS ({}) "
            "SELECT product_type, COUNT(*) FILTER (WHERE distinct_types = 1), "
            "       COUNT(*) FILTER (WHERE distinct_types > 1) "
            "FROM agreed GROUP BY product_type ORDER BY 2 DESC".format(_RESOLVE_SELECT)
        )
        by_type = cursor.fetchall()
        cursor.execute(
            "WITH agreed AS ({}) SELECT COUNT(*) FROM agreed WHERE distinct_types > 1".format(
                _RESOLVE_SELECT
            )
        )
        conflicts = cursor.fetchone()[0]
        cursor.execute("SELECT COUNT(*) FROM master_parts")
        total_master = cursor.fetchone()[0]
    return {"by_type": by_type, "conflicts": conflicts, "total_master_parts": total_master}


def conflict_examples(limit: int = 20) -> typing.List[typing.Tuple]:
    """Master parts whose best-tier distributors disagree, with what each of them said."""
    with connection.cursor() as cursor:
        cursor.execute(
            "WITH agreed AS ({select}) "
            "SELECT c.master_part_id, b.name, mp.part_number, "
            "       string_agg(DISTINCT c.source_name || '=' || c.product_type, ', ') "
            "FROM agreed a "
            "JOIN {t} c ON c.master_part_id = a.master_part_id "
            "JOIN master_parts mp ON mp.id = a.master_part_id "
            "JOIN brands b ON b.id = mp.brand_id "
            "WHERE a.distinct_types > 1 "
            "GROUP BY 1, 2, 3 LIMIT %s".format(select=_RESOLVE_SELECT, t=STAGING_TABLE),
            [limit],
        )
        return cursor.fetchall()


def apply_resolution() -> int:
    """
    Write the unanimous best-tier verdicts onto ``master_parts``. Returns rows updated.

    Only touches rows whose value actually changes, so a re-run after no rule change is a no-op
    and does not churn ``updated_at`` across 1.5M rows.
    """
    with connection.cursor() as cursor:
        cursor.execute(
            "WITH agreed AS ({select}) "
            "UPDATE master_parts mp "
            "SET product_type = a.product_type, product_type_source = a.product_type_source "
            "FROM agreed a "
            "WHERE a.master_part_id = mp.id AND a.distinct_types = 1 "
            "  AND (mp.product_type IS DISTINCT FROM a.product_type "
            "   OR mp.product_type_source IS DISTINCT FROM a.product_type_source)".format(
                select=_RESOLVE_SELECT
            )
        )
        return cursor.rowcount


def gap_report(limit: int = 15) -> typing.Dict[str, typing.Any]:
    """Where the unclassified parts are, by brand and by which distributors carry them."""
    with connection.cursor() as cursor:
        cursor.execute(
            "SELECT COUNT(*) FROM master_parts WHERE product_type IS NULL"
        )
        unclassified = cursor.fetchone()[0]
        cursor.execute(
            "SELECT b.name, COUNT(*) AS n FROM master_parts mp "
            "JOIN brands b ON b.id = mp.brand_id "
            "WHERE mp.product_type IS NULL GROUP BY 1 ORDER BY 2 DESC LIMIT %s",
            [limit],
        )
        by_brand = cursor.fetchall()
        cursor.execute(
            "SELECT p.name, COUNT(DISTINCT mp.id) AS n FROM master_parts mp "
            "JOIN provider_parts pp ON pp.master_part_id = mp.id "
            "JOIN providers p ON p.id = pp.provider_id "
            "WHERE mp.product_type IS NULL GROUP BY 1 ORDER BY 2 DESC LIMIT %s",
            [limit],
        )
        by_provider = cursor.fetchall()
    return {"unclassified": unclassified, "by_brand": by_brand, "by_provider": by_provider}


def run(
    source_names: typing.Optional[typing.Sequence[str]] = None,
    limit_per_source: typing.Optional[int] = None,
    apply_changes: bool = False,
) -> typing.Dict[str, typing.Any]:
    """
    Collect verdicts for the named sources (default: all), then report -- and only write when
    ``apply_changes`` is True. The collect phase always runs: it only touches the staging table,
    and having it populated is what makes the dry-run report real rather than an estimate.
    """
    selected = [SOURCES_BY_NAME[name] for name in (source_names or list(SOURCES_BY_NAME))]
    _ensure_staging_table()
    _clear_staging([source.name for source in selected])

    ctx = {"pcdb_by_name": _load_pcdb_lookup()}
    logger.info("%s PCdb terminology lookup: %s names.", _LOG_PREFIX, len(ctx["pcdb_by_name"]))

    per_source = {}
    for source in selected:
        per_source[source.name] = collect_source(source, ctx, limit=limit_per_source)

    result = {
        "per_source": per_source,
        "resolution": resolution_report(),
        "conflicts": conflict_examples(),
        "applied": None,
    }
    if apply_changes:
        result["applied"] = apply_resolution()
        result["gaps"] = gap_report()
    return result
