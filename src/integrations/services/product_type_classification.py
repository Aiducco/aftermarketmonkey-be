"""
Populate ``MasterPart.product_type`` (wheel / tire / part) from every distributor that ships a
usable signal. The rules themselves live in ``src.integrations.utils.product_type``; this module
is the machinery that feeds them 3.9M ``provider_parts`` rows and resolves the results.

**A wrong label is worse than no label.** Two things enforce that:

  * A source only ever produces a verdict its rules actually decided. Everything else is left
    alone, and the run reports the size of that gap rather than filling it.
  * If the distributors that agree on the *best available tier* do not agree with each other,
    the part is left NULL and counted as a conflict. We would rather hand back "we don't know"
    than pick a winner between a distributor calling something a wheel and another calling it a
    part -- that disagreement usually means one feed is miscategorised or the two rows were
    merged onto one MasterPart by mistake, and both are worth a human look.

Two phases, because a master part can be sold by up to 9 distributors and the answer depends on
all of them:

  1. **Collect.** Page each provider's ``provider_parts`` by ``(provider_id, id)`` -- the index
     ``0157`` added -- joining out to that distributor's raw table, and write one candidate row
     per verdict into ``master_part_type_candidates``.
  2. **Resolve.** One SQL statement per run: group candidates by master part, keep the best
     (lowest) tier, and write it back only where that tier is unanimous.

The staging table is deliberately not a Django model. It is a derived artifact rebuilt from
scratch on every run, so it carries no migration and is created ``UNLOGGED`` (no WAL, not
crash-safe, which is exactly right for something regenerated by re-running the command). It is
left in place afterwards on purpose: when a part's type looks wrong, the first question is
always "what did each distributor say about it", and this table is the only place that answer
exists.

    SELECT * FROM master_part_type_candidates WHERE master_part_id = 123;
"""
import dataclasses
import logging
import typing

from django.db import connection

from psycopg2 import extras as psycopg2_extras

